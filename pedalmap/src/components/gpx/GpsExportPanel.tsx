function gpxFileName(route: RouteDraft): string {
  const slug = (route.title || 'ruta')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
  return `${slug || 'ruta'}.gpx`
}

export function GpsExportPanel({ route, onPremiumRequired }: GpsExportPanelProps) {
  const { profile } = useAuth()
  const [message, setMessage] = useState<string | null>(null)

  async function ensureExportAllowed(): Promise<boolean> {
    // The Worker is the quota authority for guests, Free accounts and Premium.
    // Never let a missing/slow profile fall back to the browser-local trial.
    const claim = await claimServerGpxExport()
    if (!claim?.allowed) {
      if (claim?.error === 'quota_unavailable') {
        window.alert('No se pudo verificar la cuota GPX. Inténtalo de nuevo en unos minutos.')
      } else if (claim?.error === 'guest_identity_limit_reached') {
        onPremiumRequired?.('guest_identity_limit_reached')
      } else {
        onPremiumRequired?.('gpx_export')
      }
      return false
    }
    return true
  }

  async function noteFreeTrialUsed() {
    if (profile?.plan === 'premium') return
    // The Worker already consumed the authoritative credit before file generation.
    if (!profile) consumeGuestGpx() // UI hint only; never authorizes an export.
    track('free_trial_used', { kind: 'gpx', guest: !profile })
  }

  async function download() {
    console.log('[gpx] EXPORT BUTTON CLICK source=download')
    if (!(await ensureExportAllowed())) return
    console.log('[gpx] handler ENTER source=download')
    console.log('[gpx] platform=' + (Capacitor.isNativePlatform() ? 'native-android' : 'web'))
    const xml = exportRouteToGpx(route)
    console.log('[gpx] generated bytes=' + xml.length + ' file=' + gpxFileName(route))
    const outcome = await saveGpxFile(xml, gpxFileName(route))
    console.log('[gpx] final result=' + outcome)
    await noteFreeTrialUsed()
    track('gpx_exported', { distance_m: route.stats.distanceMeters, method: 'download' })
    setMessage(
      outcome === 'shared'
        ? 'Elige OsmAnd, Organic Maps, Garmin, Wahoo u otra app GPS en el menú compartir.'
        : outcome === 'saved'
          ? 'GPX guardado en Documentos. Ábrelo con una app GPS.'
          : profile?.plan === 'premium'
            ? 'GPX descargado. Ábrelo con OsmAnd, Organic Maps, Garmin Connect o Wahoo.'
            : 'GPX descargado · prueba Free de esta semana.',
    )
  }

  async function shareToApps() {
    console.log('[gpx] EXPORT BUTTON CLICK source=shareToApps')
    if (!(await ensureExportAllowed())) return
    console.log('[gpx] handler ENTER source=shareToApps')
    console.log('[gpx] platform=' + (Capacitor.isNativePlatform() ? 'native-android' : 'web'))
    const xml = exportRouteToGpx(route)
    console.log('[gpx] generated bytes=' + xml.length + ' file=' + gpxFileName(route))
    const outcome = await saveGpxFile(xml, gpxFileName(route))
    console.log('[gpx] final result=' + outcome)
    if (outcome === 'canceled') {
      await noteFreeTrialUsed()
      return
    }
    await noteFreeTrialUsed()
    track('gpx_exported', { distance_m: route.stats.distanceMeters, method: outcome === 'shared' ? 'share' : 'download' })
    setMessage(
      outcome === 'shared'
        ? 'Elige OsmAnd, Organic Maps, Garmin, Wahoo u otra app GPS en el menú compartir.'
        : outcome === 'saved'
          ? 'GPX guardado en Documentos. Ábrelo con una app GPS.'
          : 'GPX exportado.',
    )
  }

  const trialHint =
    profile?.plan === 'premium'
      ? null
      : freeGpxRemaining(profile) > 0
        ? `Free: ${freeGpxRemaining(profile)} GPX esta semana.`
        : 'Free: GPX de esta semana usado. Premium = ilimitado.'

  return (
    <section className="space-y-3">
      <div>
        <h2 className="font-display text-lg font-bold text-[var(--color-forest)]">
          Exportar a GPS
        </h2>
        <p className="mt-1 text-xs leading-relaxed text-[var(--color-stone)]">
          GPX hacia OsmAnd, Organic Maps, Garmin o Wahoo.
        </p>
        {trialHint && (
          <p className="mt-2 text-[11px] text-[var(--color-trail)]">{trialHint}</p>
        )}
      </div>

      <div className="flex flex-wrap gap-2">
        <Button variant="secondary" onClick={() => void (console.log('[gpx] BUTTON CLICK=Enviar a app'), void shareToApps())}>
          Enviar a app
        </Button>
        <Button variant="ghost" onClick={() => void (console.log('[gpx] BUTTON CLICK=Descargar GPX'), void download())}>
          Descargar GPX
        </Button>
      </div>

      {message && <p className="text-xs text-[var(--color-trail)]">{message}</p>}

      <ul className="space-y-1.5">
        {FREE_GPS_APPS.map((app) => (
          <li key={app.id} className="flex items-baseline justify-between gap-2 py-1">
            <div>
              <p className="text-sm font-medium text-[var(--color-forest)]">{app.name}</p>
              <p className="text-[11px] text-[var(--color-stone)]">{app.blurb}</p>
            </div>
            <a
              className="shrink-0 text-xs font-semibold text-[var(--color-trail)] underline-offset-2 hover:underline"
              href={app.url}
              target="_blank"
              rel="noreferrer"
            >
              Web
            </a>
          </li>
        ))}
      </ul>
    </section>
  )
}

/** Compact download button used on My Routes / older call sites. */
export function GPXExporter({ route, onPremiumRequired }: GpsExportPanelProps) {
  const { profile } = useAuth()

  async function download() {
    console.log('[gpx] EXPORT BUTTON CLICK source=GPXExporter')
    const claim = await claimServerGpxExport()
    if (!claim?.allowed) {
      if (claim?.error === 'quota_unavailable') {
        window.alert('No se pudo verificar la cuota GPX. Inténtalo de nuevo en unos minutos.')
      } else if (claim?.error === 'guest_identity_limit_reached') {
        onPremiumRequired?.('guest_identity_limit_reached')
      } else {
        onPremiumRequired?.('gpx_export')
      }
      return
    }
    console.log('[gpx] handler ENTER source=GPXExporter')
    const xml = exportRouteToGpx(route)
    console.log('[gpx] calling saveGpxFile route=' + route.title)
    const outcome = await saveGpxFile(xml, gpxFileName(route))
    console.log('[gpx] save outcome=' + outcome + ' route=' + route.title)
    if (profile?.plan !== 'premium') {
      if (!profile) consumeGuestGpx() // UI hint only; the Worker owns the quota.
      track('free_trial_used', { kind: 'gpx', guest: !profile })
    }
    track('gpx_exported', { distance_m: route.stats.distanceMeters, method: 'download' })
  }

  return (
    <Button variant="ghost" onClick={() => void download()}>
      Descargar GPX
    </Button>
  )
}
